let x = 10;
let y = 3;

// Addition (+)
console.log(x + y); 

// Subtraction (-)
console.log(x - y);  

// Multiplication (*)
console.log(x * y);  

// Division (/)
console.log(x / y);

//Modulus
console.log(10 % 3);  

// Exponentiation (**) 
console.log(2 ** 3);

let score = 10;

// Increment (++) 
score++; 
console.log(score); 

// Decrement (--) 
score--; 
console.log(score); 

let customColor = "";
let defaultColor = "blue";

// If customColor is falsy (empty string), it uses defaultColor
let activeColor = customColor || defaultColor; 

console.log(activeColor); // Outputs: "blue"

